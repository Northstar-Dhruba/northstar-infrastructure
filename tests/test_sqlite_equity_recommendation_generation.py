def test_u_the_kind_and_the_proposal_are_bound_by_the_database(world: World) -> None:
    _with_schema(world)
    proposed, _ = records(world.proposed())
    not_eligible, _ = records(world.not_eligible())
    unresolved, _ = records(world.unresolved())
    none = {"proposal_document": None, "proposal_fingerprint": None, "proposal_format": None}
    proposal = {
        "proposal_document": proposed.proposal_document,
        "proposal_fingerprint": proposed.proposal_fingerprint,
        "proposal_format": "northstar.equity-recommendation-proposal/1",
    }
    for row in (
        _row_with(proposed, **none),  # PROPOSED without its proposal
        _row_with(proposed, proposal_document=None),
        _row_with(not_eligible, **proposal),  # NOT_ELIGIBLE with a proposal
        _row_with(unresolved, **proposal),  # UNRESOLVED with a proposal
        _row_with(unresolved, disposition_kind="PROPOSED"),  # kind against its document
        _row_with(proposed, disposition_kind="ISSUED"),  # no such kind
    ):
        with pytest.raises(sqlite3.IntegrityError, match="CHECK"):
            _insert(world.database, DISPOSITIONS, adapter_module.DISPOSITION_COLUMNS, row)
    tables = {n for n, (k, _) in _schema_objects(world.database).items() if k == "table"}
    assert {t for t in tables if "recommendation" in t} == {DISPOSITIONS, ATTEMPTS}
    assert _counts(world.database) == (0, 0)  # no orphan proposal anywhere


