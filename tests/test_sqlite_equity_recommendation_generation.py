def _rows(database: Path, table: str) -> list[dict[str, Any]]:
    with closing(raw(database)) as connection:
        connection.row_factory = sqlite3.Row
        return [dict(row) for row in connection.execute(f"SELECT * FROM {table}")]  # noqa: S608


def _schema_objects(database: Path) -> dict[str, tuple[str, str]]:
    with closing(raw(database)) as connection:
        return {
            name: (kind, sql)
            for kind, name, sql in connection.execute(
                "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL"
            )
        }


def _check_database(database: Path) -> None:
    with closing(raw(database)) as connection:
        assert connection.execute("PRAGMA integrity_check").fetchall() == [("ok",)]
        assert connection.execute("PRAGMA foreign_key_check").fetchall() == []


def _bypass(
    database: Path,
    *statements: tuple[str, tuple[object, ...]],
    drop: tuple[str, ...] = (),
    checks: bool = True,
    foreign_keys: bool = True,
) -> None:
    """Test-only corruption of a disposable database: drop triggers, relax checks, write."""
    with closing(sqlite3.connect(database, isolation_level=None)) as connection:
        connection.execute(f"PRAGMA foreign_keys = {'ON' if foreign_keys else 'OFF'}")
        if not checks:
            connection.execute("PRAGMA ignore_check_constraints = ON")
        for trigger in drop:
            connection.execute(f"DROP TRIGGER IF EXISTS {trigger}")
        for statement, parameters in statements:
            connection.execute(statement, parameters)


def _insert(
    database: Path, table: str, columns: tuple[str, ...], values: tuple[object, ...]
) -> None:
    with closing(raw(database)) as connection:
        connection.execute(
            f"INSERT INTO {table} ({', '.join(columns)}) "  # noqa: S608
            f"VALUES ({', '.join('?' * len(columns))})",
            values,
        )


def _entry(database: Path, sequence: int) -> dict[str, Any]:
    with closing(raw(database)) as connection:
        connection.row_factory = sqlite3.Row
        return dict(
            connection.execute(
                f"SELECT * FROM {_ENTRIES} WHERE sequence = ?", (sequence,)
            ).fetchone()  # noqa: S608
        )


def _with_schema(world: World) -> None:
    """Have an adapter connection add the generation schema to the evidence database."""
    assert world.store().load_disposition("eirk1-sha256:" + "0" * 64) is None


def _with_document(
    disposition: EquityRecommendationGenerationDisposition, **changes: object
) -> tuple[object, ...]:
    """A raw disposition row whose assessment document and columns agree, with ``changes``.

    ``changes`` name candidate source fields (or ``candidate_sequence`` and
    ``manifest_fingerprint``); the CHECK constraints pass, so only the
    source triggers and foreign keys can refuse the row.
    """
    document = json.loads(disposition.assessment_document)
    candidate = document["inputs"]["candidate"]
    for name, value in changes.items():
        (candidate if name in candidate else candidate["source"])[name] = value
    text = json.dumps(document, sort_keys=True, separators=(",", ":"))
    row = list(adapter_module.disposition_row(disposition))
    row[adapter_module.DISPOSITION_COLUMNS.index("assessment_document")] = text
    for name, value in changes.items():
        row[adapter_module.DISPOSITION_COLUMNS.index(name)] = value
    return tuple(row)


