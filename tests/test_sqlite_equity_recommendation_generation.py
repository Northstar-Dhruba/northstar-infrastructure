        f"UPDATE {DISPOSITIONS} SET candidate_entry_fingerprint = candidate_entry_fingerprint",
        f"UPDATE {DISPOSITIONS} SET evidence_snapshot_id = evidence_snapshot_id",
        f"DELETE FROM {DISPOSITIONS}",
        f"INSERT OR REPLACE INTO {DISPOSITIONS} SELECT * FROM {DISPOSITIONS}",
        f"REPLACE INTO {DISPOSITIONS} SELECT * FROM {DISPOSITIONS}",
        f"INSERT OR IGNORE INTO {DISPOSITIONS} SELECT * FROM {DISPOSITIONS}",
        f"UPDATE {ATTEMPTS} SET status = status",
        f"DELETE FROM {ATTEMPTS}",
        f"INSERT OR REPLACE INTO {ATTEMPTS} SELECT * FROM {ATTEMPTS}",
