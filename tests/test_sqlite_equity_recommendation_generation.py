    first = world.recorder().execute(audit)
    again = world.recorder().execute(world.attempt_only())
    assert (first.outcome, again.outcome) == (_O.COMMITTED, _O.EQUIVALENT_COMMITTED)
    assert world.store().load_attempt(attempt.attempt_identity) == attempt
    (row,) = _rows(world.database, ATTEMPTS)
